from collections import OrderedDict

class MapReduce:

    def __init__(self):
        self.intermediate = OrderedDict()
        self.result = []

    def emitIntermediate(self, key, value):
        self.intermediate.setdefault(key, [])
        self.intermediate[key].append(value)

    def emit(self, value):
        i, j, val = value
        self.result[i][j] = val

    def execute(self, matrix1, matrix2, mapper, reducer):
        n = len(matrix1)
        m = len(matrix2[0])

        self.result = [[0] * m for _ in range(n)]

        mapper(matrix1, matrix2)

        for key in self.intermediate:
            reducer(key, self.intermediate[key])

        print("\nResult Matrix:")
        for row in self.result:
            print(*row)


mapReducer = None


def mapper(matrix1, matrix2):
    n = len(matrix1)
    rows_b = len(matrix2)
    cols_b = len(matrix2[0])

    for i in range(n):
        for j in range(cols_b):

            mapReducer.emitIntermediate((i, j), matrix1[i])

            column = []
            for k in range(rows_b):
                column.append(matrix2[k][j])

            mapReducer.emitIntermediate((i, j), column)


def reducer(key, list_of_values):
    row = list_of_values[0]
    column = list_of_values[1]

    dot_product = 0

    for i in range(len(row)):
        dot_product += row[i] * column[i]

    mapReducer.emit((key[0], key[1], dot_product))


