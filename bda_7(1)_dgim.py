class DGIM:
    def __init__(self, window_size):
        self.window_size = window_size
        self.buckets = []
        self.timestamp = 0

    def add_bit(self, bit):
        self.timestamp += 1

        if bit == 1:
            self.buckets.append([1, self.timestamp])
            self.merge()

        # Remove old buckets
        self.buckets = [
            b for b in self.buckets
            if b[1] > self.timestamp - self.window_size
        ]

    def merge(self):
        while True:
            merged = False

            for size in [1, 2, 4, 8, 16, 32, 64]:
                indexes = [
                    i for i, b in enumerate(self.buckets)
                    if b[0] == size
                ]

                if len(indexes) > 2:
                    i1 = indexes[0]
                    i2 = indexes[1]

                    new_bucket = [
                        size * 2,
                        self.buckets[i2][1]
                    ]

                    self.buckets.pop(i2)
                    self.buckets.pop(i1)
                    self.buckets.insert(i1, new_bucket)

                    merged = True
                    break

            if not merged:
                break

    def query(self):
        total = 0

        for bucket in self.buckets:
            total += bucket[0]

        return total


