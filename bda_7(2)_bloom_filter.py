for i in range(n):
    word = input()
    bloom.add(word)


# False Positive Probability

probability = (1 - math.exp(
    -(hash_count * n) / size
)) ** hash_count

print("\nSize of bit array:", size)

print("False Positive Probability:",
      round(probability, 3))

print("Number of hash functions:", hash_count)


# Searching Elements

