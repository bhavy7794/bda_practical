import hashlib
import math

class BloomFilter:

    def __init__(self, size, hash_count):
        self.size = size
        self.hash_count = hash_count
        self.bit_array = [0] * size

    def _hashes(self, item):
        indexes = []

        for i in range(self.hash_count):
            data = str(item) + str(i)

            hash_value = int(
                hashlib.md5(data.encode()).hexdigest(), 16
            )

            indexes.append(hash_value % self.size)

        return indexes

    def add(self, item):
        for index in self._hashes(item):
            self.bit_array[index] = 1

    def contains(self, item):
        for index in self._hashes(item):
            if self.bit_array[index] == 0:
                return False

        return True


# Main Program

size = int(input("Enter size of bit array: "))
hash_count = int(input("Enter number of hash functions: "))

bloom = BloomFilter(size, hash_count)

